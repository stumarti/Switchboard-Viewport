// Draw a 96x96 error icon at (x,y), tinting black pixels to 'tint'.
template<typename TDisplay>
void drawErrorIcon(TDisplay& display, const uint8_t* bmp, int16_t x, int16_t y, uint16_t tint) {
  int idx=0;
  for(int16_t row=0;row<96;row++){
    for(int16_t col=0;col<96;col+=2){
      uint8_t b=pgm_read_byte(&bmp[idx++]);
      uint8_t hi=(b>>4)&0xF, lo=b&0xF;
      if(hi==1) display.drawPixel(x+col,  y+row,tint);
      if(lo==1) display.drawPixel(x+col+1,y+row,tint);
    }
  }
}