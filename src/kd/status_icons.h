// Draw a 32x32 status icon, remapping black pixels to iconColor.
template<typename TDisplay>
void drawStatusIcon(TDisplay& display, const uint8_t* bmp,
                    int16_t x, int16_t y, uint16_t iconColor) {
  static const uint16_t BASE[] = {
    GxEPD_WHITE, GxEPD_BLACK, GxEPD_RED,
    GxEPD_YELLOW, GxEPD_GREEN, GxEPD_BLUE
  };
  int idx=0;
  for(int16_t row=0;row<32;row++) {
    for(int16_t col=0;col<32;col+=2) {
      uint8_t b=pgm_read_byte(&bmp[idx++]);
      uint8_t hi=(b>>4)&0xF, lo=b&0xF;
      uint16_t cHi=(hi==1)?iconColor:(hi<6?BASE[hi]:GxEPD_WHITE);
      uint16_t cLo=(lo==1)?iconColor:(lo<6?BASE[lo]:GxEPD_WHITE);
      display.drawPixel(x+col,  y+row,cHi);
      display.drawPixel(x+col+1,y+row,cLo);
    }
  }
}