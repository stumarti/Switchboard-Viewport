// Draw a heating icon at (x,y) at the given size, tinting black pixels to 'tint'.
// Index 0 (white) is treated as TRANSPARENT so the panel colour shows through.
template<typename TDisplay>
void drawHeatIcon(TDisplay& display, const uint8_t* bmp, int16_t x, int16_t y, int16_t sz, uint16_t tint) {
  static const uint16_t COLORS[] = { GxEPD_WHITE, GxEPD_BLACK, GxEPD_RED, GxEPD_YELLOW, GxEPD_GREEN, GxEPD_BLUE };
  int idx=0;
  for(int16_t row=0;row<sz;row++){
    for(int16_t col=0;col<sz;col+=2){
      uint8_t b=pgm_read_byte(&bmp[idx++]);
      uint8_t hi=(b>>4)&0xF, lo=b&0xF;
      // Only draw non-white pixels; index 1 (black) is recoloured to tint.
      if(hi!=0 && hi<6) display.drawPixel(x+col,   y+row, (hi==1)?tint:COLORS[hi]);
      if(lo!=0 && lo<6) display.drawPixel(x+col+1, y+row, (lo==1)?tint:COLORS[lo]);
    }
  }
}