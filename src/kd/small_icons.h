// Return wind arrow bitmap for a bearing in degrees (0=N, 90=E, etc.)
inline const uint8_t* windArrow(float bearing) {
  int sector = (int)((bearing + 22.5f) / 45.0f) % 8;
  static const uint8_t* arrows[] = {
    si_wind_n, si_wind_ne, si_wind_e, si_wind_se,
    si_wind_s, si_wind_sw, si_wind_w, si_wind_nw
  };
  return arrows[sector];
}