template<typename TDisplay>
void drawTinyIcon(TDisplay& display, const uint8_t* bmp, int16_t x, int16_t y, uint16_t tint) {
  static const uint16_t COLORS[] = { GxEPD_WHITE, GxEPD_BLACK, GxEPD_RED, GxEPD_YELLOW, GxEPD_GREEN, GxEPD_BLUE };
  int idx=0;
  for(int16_t row=0;row<16;row++){
    for(int16_t col=0;col<16;col+=2){
      uint8_t b=pgm_read_byte(&bmp[idx++]);
      uint8_t hi=(b>>4)&0xF, lo=b&0xF;
      uint16_t cHi=(hi==1)?tint:(hi<6?COLORS[hi]:GxEPD_WHITE);
      uint16_t cLo=(lo==1)?tint:(lo<6?COLORS[lo]:GxEPD_WHITE);
      if(hi<6) display.drawPixel(x+col,  y+row,cHi);
      if(lo<6) display.drawPixel(x+col+1,y+row,cLo);
    }
  }
}

