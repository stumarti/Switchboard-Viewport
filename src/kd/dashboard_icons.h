// Draw a 44x44 dashboard icon at (x,y).
template<typename TDisplay>
void drawDashIcon(TDisplay& display, const uint8_t* bmp, int16_t x, int16_t y) {
  static const uint16_t COLORS[] = {
    GxEPD_WHITE, GxEPD_BLACK, GxEPD_RED,
    GxEPD_YELLOW, GxEPD_GREEN, GxEPD_BLUE
  };
  int idx=0;
  for(int16_t row=0;row<44;row++) {
    for(int16_t col=0;col<44;col+=2) {
      uint8_t b=pgm_read_byte(&bmp[idx++]);
      uint8_t hi=(b>>4)&0xF, lo=b&0xF;
      if(hi<6) display.drawPixel(x+col,  y+row,COLORS[hi]);
      if(lo<6) display.drawPixel(x+col+1,y+row,COLORS[lo]);
    }
  }
}